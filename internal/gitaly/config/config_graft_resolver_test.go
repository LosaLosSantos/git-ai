package config

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestGraftResolverValidateSendRules(t *testing.T) {
	t.Parallel()

	valid := GraftResolver{Enabled: true, Command: []string{"graft-resolve"}}
	require.NoError(t, valid.validate())

	withRules := valid
	withRules.Lockfiles = []string{"Gemfile.lock"}
	withRules.GeneratedMarkers = []string{`^// Generated by \w+`}
	withRules.Minified = GraftResolverMinified{Globs: []string{"*.min.html"}, AverageLineBytes: 200, LongestLineBytes: 4000}
	require.NoError(t, withRules.validate())

	for name, tc := range map[string]struct {
		mutate func(*GraftResolver)
		want   string
	}{
		"lockfile with a slash": {func(r *GraftResolver) { r.Lockfiles = []string{"web/yarn.lock"} }, "must be a base name"},
		"empty lockfile":        {func(r *GraftResolver) { r.Lockfiles = []string{""} }, "must be a base name"},
		"bad marker":            {func(r *GraftResolver) { r.GeneratedMarkers = []string{"(unclosed"} }, "generated marker"},
		"empty marker":          {func(r *GraftResolver) { r.GeneratedMarkers = []string{""} }, "empty generated marker"},
		"bad minified glob":     {func(r *GraftResolver) { r.Minified.Globs = []string{"[x"} }, "minified glob"},
		"minified glob path":    {func(r *GraftResolver) { r.Minified.Globs = []string{"dist/*.js"} }, "base-name glob"},
		"negative threshold":    {func(r *GraftResolver) { r.Minified.LongestLineBytes = -1 }, "must not be negative"},
	} {
		t.Run(name, func(t *testing.T) {
			r := valid
			tc.mutate(&r)
			err := r.validate()
			require.Error(t, err)
			require.True(t, strings.Contains(err.Error(), tc.want), "error %q lacks %q", err, tc.want)
		})
	}
}

func TestGraftResolverMinifiedDefaults(t *testing.T) {
	t.Parallel()

	var m GraftResolverMinified
	require.Equal(t, DefaultGraftResolverMinifiedAverageLineBytes, m.AverageLineBytesOrDefault())
	require.Equal(t, DefaultGraftResolverMinifiedLongestLineBytes, m.LongestLineBytesOrDefault())
	m = GraftResolverMinified{AverageLineBytes: 10, LongestLineBytes: 20}
	require.Equal(t, 10, m.AverageLineBytesOrDefault())
	require.Equal(t, 20, m.LongestLineBytesOrDefault())
}
