func TestGraftResolverValidateSendRules(t *testing.T) {
	t.Parallel()

	valid := GraftResolver{Enabled: true, Command: []string{"graft-resolve"}}
	require.NoError(t, valid.validate())

	withRules := valid
	withRules.Lockfiles = []string{"Gemfile.lock"}
	withRules.GeneratedMarkers = []string{`^// Generated by \w+`}
	withRules.Minified = GraftResolverMinified{Globs: []string{"*.min.html"}, AverageLineBytes: 200, LongestLineBytes: 4000}
	require.NoError(t, withRules.validate())

	for name, tc := range map[string]struct {
		mutate func(*GraftResolver)
		want   string
	}{
		"lockfile with a slash": {func(r *GraftResolver) { r.Lockfiles = []string{"web/yarn.lock"} }, "must be a base name"},
		"empty lockfile":        {func(r *GraftResolver) { r.Lockfiles = []string{""} }, "must be a base name"},
		"bad marker":            {func(r *GraftResolver) { r.GeneratedMarkers = []string{"(unclosed"} }, "generated marker"},
		"empty marker":          {func(r *GraftResolver) { r.GeneratedMarkers = []string{""} }, "empty generated marker"},
		"bad minified glob":     {func(r *GraftResolver) { r.Minified.Globs = []string{"[x"} }, "minified glob"},
		"minified glob path":    {func(r *GraftResolver) { r.Minified.Globs = []string{"dist/*.js"} }, "base-name glob"},
		"negative threshold":    {func(r *GraftResolver) { r.Minified.LongestLineBytes = -1 }, "must not be negative"},
	} {
		t.Run(name, func(t *testing.T) {
			r := valid
			tc.mutate(&r)
			err := r.validate()
			require.Error(t, err)
			require.True(t, strings.Contains(err.Error(), tc.want), "error %q lacks %q", err, tc.want)
		})
	}
}

func TestGraftResolverValidateVerify(t *testing.T) {
	t.Parallel()

	// Off by default, and validated even without a resolver (agents' resolutions get it too).
	require.NoError(t, GraftResolver{}.validate())
	require.NoError(t, GraftResolver{Verify: GraftResolverVerify{Enabled: true, Command: []string{"make", "test"}}}.validate())

	d, err := GraftResolverVerify{}.TimeoutOrDefault()
	require.NoError(t, err)
	require.Equal(t, "5m0s", d.String())

	for name, v := range map[string]GraftResolverVerify{
		"no command":    {Enabled: true},
		"empty program": {Enabled: true, Command: []string{""}},
		"bad timeout":   {Enabled: true, Command: []string{"x"}, Timeout: "soon"},
		"zero timeout":  {Enabled: true, Command: []string{"x"}, Timeout: "0s"},
	} {
		require.Error(t, GraftResolver{Verify: v}.validate(), name)
	}
}

func TestGraftResolverMinifiedDefaults(t *testing.T) {
	t.Parallel()

	var m GraftResolverMinified
	require.Equal(t, DefaultGraftResolverMinifiedAverageLineBytes, m.AverageLineBytesOrDefault())
	require.Equal(t, DefaultGraftResolverMinifiedLongestLineBytes, m.LongestLineBytesOrDefault())
	m = GraftResolverMinified{AverageLineBytes: 10, LongestLineBytes: 20}
	require.Equal(t, 10, m.AverageLineBytesOrDefault())
	require.Equal(t, 20, m.LongestLineBytesOrDefault())
}

// TestGraftResolverValidateBuildable: a resolver configuration that the server could not build is
// a startup error, not a resolver turned off: an empty command, a URL that is no http or https URL
// with a host, a token file that cannot be read or is empty, a negative check_concurrency,
// resolve_concurrency or resolve_rounds, or a max_file_bytes over the bound of a check request.
func TestGraftResolverValidateBuildable(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	token := filepath.Join(dir, "token")
	require.NoError(t, os.WriteFile(token, []byte("secret\n"), 0o600))
	empty := filepath.Join(dir, "empty")
	require.NoError(t, os.WriteFile(empty, []byte(" \n"), 0o600))

	byURL := GraftResolver{Enabled: true, URL: "https://resolver.example:8443/resolve", TokenFile: token}
	require.NoError(t, byURL.validate())

	// max_file_bytes may be exactly the bound, not one byte more.
	atBound := GraftResolver{Enabled: true, Command: []string{"graft-resolve"}, MaxFileBytes: GraftResolverMaxCheckFileBytes}
	require.NoError(t, atBound.validate())

	for name, tc := range map[string]struct {
		r    GraftResolver
		want string
	}{
		"empty command":               {GraftResolver{Command: []string{""}}, "empty command"},
		"url without scheme":          {GraftResolver{URL: "resolver.example/resolve"}, "http or https URL with a host"},
		"url of another kind":         {GraftResolver{URL: "ftp://resolver.example/"}, "http or https URL with a host"},
		"url without host":            {GraftResolver{URL: "http:///resolve"}, "http or https URL with a host"},
		"missing token file":          {GraftResolver{URL: "https://resolver.example/", TokenFile: filepath.Join(dir, "absent")}, "read token file"},
		"empty token file":            {GraftResolver{URL: "https://resolver.example/", TokenFile: empty}, "is empty"},
		"proposal_ttl not a duration": {GraftResolver{Command: []string{"graft-resolve"}, ProposalTTL: "a week"}, "proposal_ttl"},
		"proposal_ttl zero":           {GraftResolver{Command: []string{"graft-resolve"}, ProposalTTL: "0s"}, "proposal_ttl"},
		"negative check_concurrency": {
			GraftResolver{Command: []string{"graft-resolve"}, CheckConcurrency: -1}, "must not be negative",
		},
		"negative resolve_concurrency": {
			GraftResolver{Command: []string{"graft-resolve"}, ResolveConcurrency: -1}, "must not be negative",
		},
		"negative verify_concurrency": {
			GraftResolver{Command: []string{"graft-resolve"}, VerifyConcurrency: -1}, "must not be negative",
		},
		"negative resolve_rounds": {
			GraftResolver{Command: []string{"graft-resolve"}, ResolveRounds: -1}, "must not be negative",
		},
		"max_file_bytes over the bound": {
			GraftResolver{Command: []string{"graft-resolve"}, MaxFileBytes: GraftResolverMaxCheckFileBytes + 1}, "max_file_bytes",
		},
	} {
		t.Run(name, func(t *testing.T) {
			tc.r.Enabled = true
			err := tc.r.validate()
			require.Error(t, err)
			require.True(t, strings.Contains(err.Error(), tc.want), "error %q lacks %q", err, tc.want)
		})
	}

	ttl, err := GraftResolver{}.ProposalTTLOrDefault()
	require.NoError(t, err)
	require.Equal(t, "168h0m0s", ttl.String())
	require.Equal(t, DefaultGraftResolverCheckConcurrency, GraftResolver{}.CheckConcurrencyOrDefault())
	require.Equal(t, 5, GraftResolver{CheckConcurrency: 5}.CheckConcurrencyOrDefault())
	require.Equal(t, DefaultGraftResolverResolveConcurrency, GraftResolver{}.ResolveConcurrencyOrDefault())
	require.Equal(t, 4, GraftResolver{ResolveConcurrency: 4}.ResolveConcurrencyOrDefault())
	require.Equal(t, DefaultGraftResolverVerifyConcurrency, GraftResolver{}.VerifyConcurrencyOrDefault())
	require.Equal(t, 3, GraftResolver{VerifyConcurrency: 3}.VerifyConcurrencyOrDefault())
	require.Equal(t, DefaultGraftResolverResolveRounds, GraftResolver{}.ResolveRoundsOrDefault())
	require.Equal(t, 7, GraftResolver{ResolveRounds: 7}.ResolveRoundsOrDefault())
}

// TestGraftResolverCheckBounds: a file of GraftResolverMaxCheckFileBytes, its three sides and its
// resolution, with a path of about 4 KiB, fits one check batch, and so one request.
func TestGraftResolverCheckBounds(t *testing.T) {
	t.Parallel()

	const path = 4 << 10
	require.LessOrEqual(t, int64(4*GraftResolverMaxCheckFileBytes+path), int64(GraftResolverCheckBatchBytes))
	require.LessOrEqual(t, int64(GraftResolverCheckBatchBytes)*4/3+GraftResolverCheckEnvelopeBytes, int64(GraftResolverMaxCheckRequestBytes))
}
