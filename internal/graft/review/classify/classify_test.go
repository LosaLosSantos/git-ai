package classify

import (
	"testing"

	"github.com/feder-cr/open_scion/proto/go/gitalypb"
)

const (
	clsCode        = gitalypb.ReviewFile_CHANGE_CLASS_CODE_UNSPECIFIED
	clsComment     = gitalypb.ReviewFile_CHANGE_CLASS_COMMENT_ONLY
	clsDocs        = gitalypb.ReviewFile_CHANGE_CLASS_DOCS
	clsTests       = gitalypb.ReviewFile_CHANGE_CLASS_TESTS
	clsGenerated   = gitalypb.ReviewFile_CHANGE_CLASS_GENERATED
	clsConfig      = gitalypb.ReviewFile_CHANGE_CLASS_CONFIG
	absentSentinel = "\x00absent"
)

type fileCase struct {
	name string
	path string
	// old and new are the file contents. The sentinel absentSentinel means
	// the file does not exist in that version.
	old, new string
	want     gitalypb.ReviewFile_ChangeClass
}

// content returns the bytes for a version, nil when the version is absent.
func content(s string) []byte {
	if s == absentSentinel {
		return nil
	}
	return []byte(s)
}

func runFileCases(t *testing.T, cases []fileCase) {
	t.Helper()
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, reason := File(tc.path, content(tc.old), content(tc.new))
			if got != tc.want {
				t.Fatalf("File(%q) = %v (%s), want %v", tc.path, got, reason, tc.want)
			}
			if reason == "" {
				t.Fatal("reason is empty")
			}
			again, againReason := File(tc.path, content(tc.old), content(tc.new))
			if again != got || againReason != reason {
				t.Fatalf("File is not deterministic: %v/%q then %v/%q", got, reason, again, againReason)
			}
		})
	}
}

