// Spec: any lexer uncertainty (EOF inside string/comment) → CODE, even when whitespace-only.
func TestSpecLexerUncertaintyIsCode(t *testing.T) {
	cases := []struct {
		name string
		path string
		old  string
		new  string
	}{
		{"EOF inside block comment", "pkg/a.go", "var x = 1 /* open", "var  x = 1 /* open"},
		{"EOF inside string", "pkg/a.go", "var s = \"abc", "var  s = \"abc"},
		{"EOF inside python triple-quoted string", "pkg/mod.py", "x = \"\"\"abc", "x  = \"\"\"abc"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, reason := File(tc.path, []byte(tc.old), []byte(tc.new))
			if got != gitalypb.ReviewFile_CHANGE_CLASS_CODE_UNSPECIFIED {
				t.Fatalf("File class = %v, want CODE (reason %q)", got, reason)
			}
		})
	}
}

// Spec: binary content → CODE unless a path rule matches.
func TestSpecBinaryContent(t *testing.T) {
	binA := []byte{0x00, 0x01, 0xff, 0xfe}
	binB := []byte{0x00, 0x01, 0xfe, 0xff}

	if got, reason := File("pkg/blob.go", binA, binB); got != gitalypb.ReviewFile_CHANGE_CLASS_CODE_UNSPECIFIED {
		t.Errorf("binary change in .go file class = %v, want CODE (reason %q)", got, reason)
	}
	if got, reason := File("pkg/blob.go", binA, binA); got != gitalypb.ReviewFile_CHANGE_CLASS_CODE_UNSPECIFIED {
		t.Errorf("identical binary content class = %v, want CODE (reason %q)", got, reason)
	}
	if got, reason := File("assets/logo.md", binA, binB); got != gitalypb.ReviewFile_CHANGE_CLASS_DOCS {
		t.Errorf("binary change under path rule .md class = %v, want DOCS (reason %q)", got, reason)
	}
}

// Spec: every result carries a reason; the decision is deterministic and nothing panics on edge inputs.
func TestSpecReasonNonEmptyAndDeterministic(t *testing.T) {
	inputs := []struct {
		path string
		old  []byte
		new  []byte
	}{
		{"pkg/a.go", []byte("// a\npackage a\n"), []byte("// b\npackage a\n")},
		{"pkg/a.go", []byte("package a\n"), []byte("package b\n")},
		{"pkg/a.go", []byte{}, []byte{}},
		{"pkg/a.go", nil, nil},
		{"pkg/a.go", []byte("\"unterminated"), []byte("\"unterminated")},
		{"x.unknownext", []byte("abc"), []byte("abd")},
		{"", nil, []byte("x")},
	}
	for _, in := range inputs {
		c1, r1 := File(in.path, in.old, in.new)
		c2, r2 := File(in.path, in.old, in.new)
		if c1 != c2 || r1 != r2 {
			t.Errorf("File(%q) not deterministic: (%v,%q) vs (%v,%q)", in.path, c1, r1, c2, r2)
		}
		if r1 == "" {
			t.Errorf("File(%q) returned empty reason for class %v", in.path, c1)
		}
	}
}
