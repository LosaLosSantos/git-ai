// neverSendVectors are the test vectors of testdata/never-send.json, which the bench of
// tools/graft-agents checks too.
type neverSendVectors struct {
	MaxFileBytes int64 `json:"max_file_bytes"`
	Cases        []struct {
		Name      string `json:"name"`
		Path      string `json:"path"`
		Generated bool   `json:"generated"`
		Sides     []*[]struct {
			Text   string `json:"text"`
			Repeat int    `json:"repeat"`
		} `json:"sides"`
		Want string `json:"want"`
	} `json:"cases"`
}

func TestSendRulesVectors(t *testing.T) {
	t.Parallel()

	data, err := os.ReadFile("testdata/never-send.json")
	require.NoError(t, err)
	var v neverSendVectors
	require.NoError(t, json.Unmarshal(data, &v))
	require.NotEmpty(t, v.Cases)

	rules, err := NewSendRules(config.GraftResolver{MaxFileBytes: v.MaxFileBytes})
	require.NoError(t, err)

	for _, c := range v.Cases {
		var sides [][]byte
		for _, side := range c.Sides {
			if side == nil {
				sides = append(sides, nil)
				continue
			}
			var b strings.Builder
			for _, part := range *side {
				b.WriteString(strings.Repeat(part.Text, max(1, part.Repeat)))
			}
			sides = append(sides, []byte(b.String()))
		}
		require.Equal(t, c.Want, rules.Reason(c.Path, c.Generated, sides...), c.Name)
	}
}

func TestSendRulesConfiguredExtensions(t *testing.T) {
	t.Parallel()

	rules, err := NewSendRules(config.GraftResolver{
		Lockfiles:        []string{"Gemfile.lock"},
		GeneratedMarkers: []string{`^// Generated by mytool`},
		Minified: config.GraftResolverMinified{
			Globs:            []string{"*.min.html"},
			AverageLineBytes: 50,
			LongestLineBytes: 100,
		},
	})
	require.NoError(t, err)

	require.Equal(t, NotSentLockfile, rules.Reason("Gemfile.lock", false, []byte("x\n")))
	require.Equal(t, NotSentLockfile, rules.Reason("go.sum", false, []byte("x\n")), "the built-in list stays")
	require.Equal(t, NotSentGenerated, rules.Reason("a.go", false, []byte("// Generated by mytool\npackage a\n")))
	require.Equal(t, NotSentMinified, rules.Reason("index.min.html", false, []byte("<p>\n")))
	require.Equal(t, NotSentMinified, rules.Reason("a.js", false, []byte(strings.Repeat(strings.Repeat("x", 60)+"\n", 40))), "average above 50")
	require.Equal(t, "", rules.Reason("a.js", false, []byte(strings.Repeat(strings.Repeat("x", 40)+"\n", 60))))
	require.True(t, rules.TooLarge(config.DefaultGraftResolverMaxFileBytes+1))
	require.False(t, rules.TooLarge(config.DefaultGraftResolverMaxFileBytes))
}
